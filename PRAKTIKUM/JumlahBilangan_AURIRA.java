package PRAKTIKUM;
public class JumlahBilangan_AURIRA {

    public static void main(String[] args) {
        
        int totalBilangan = 0;
        for (int i = 1; i <= 10; i++) {
            totalBilangan += i;
        }
        
        System.out.println("Jumlah bilangan dari 1 sampai 10: " + totalBilangan);
    }
}
