    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
       try {
            String nama = txtNama.getText().trim();
            
            if (nama.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Nama mahasiswa harus diisi!");
                txtNama.requestFocus();
                return;
            }
            
            if (txtTugas.getText().trim().isEmpty()
                    || txtUTS.getText().trim().isEmpty()

                    || txtUAS.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Semua nilai harus diisi!");
                return;
            }
            
            double tugas = Double.parseDouble(txtTugas.getText().trim());
            double uts = Double.parseDouble(txtUTS.getText().trim());
            double uas = Double.parseDouble(txtUAS.getText().trim());
            
            if (tugas < 0 || tugas > 100
                    || uts < 0 || uts > 100
                    || uas < 0 || uas > 100) {
                JOptionPane.showMessageDialog(this, "Setiap nilai harus berada pada rentang 0-100!");
                return;
            }
            
            double rata = (tugas + uts + uas) / 3.0;
            String status = (rata >= 75) ? "LULUS" : "TIDAK LULUS";
            
            String grade;
            if (rata >= 90) {
                grade = "A";
            } else if (rata <= 80) {
                grade = "B";
            } else if (rata <= 70) {
                grade = "C";
            } else if (rata <= 60) {
                grade = "D";
            } else {
                grade = "E";
            }
            
            txtHasil.setText(
                    "Nama: " + nama
                    + "\nNilai Tugas: " + tugas
                    + "\nNilai UTS: " + uts
                    + "\nNilai UAS: " + uas
                    + "\nRata-rata: " + String.format("%.2f", rata)
                    + "\nStatus: " + status
                    + "\nGrade: " + grade
            );
        
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Nilai harus diisi dengan angka yang valid!");
}
    }//GEN-LAST:event_btnHitungActionPerformed

