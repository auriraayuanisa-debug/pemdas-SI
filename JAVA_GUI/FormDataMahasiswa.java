    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String nim = txtNIM.getText().trim();
        String nama = txtNama.getText().trim();
        
        if (nim.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "NIM dan nama wajib diisi!");
            return;
        }
        
        String prodi = String.valueOf(cmbProdi.getSelectedItem());
        String jenisKelamin;
        
        if (rdoLaki.isSelected()) {
            jenisKelamin = "Laki-laki";
        } else if (rdoPerempuan.isSelected()) {
            jenisKelamin = "Perempuan";
        } else {
            JOptionPane.showMessageDialog(this, "Pilih jenis kelamin!");
            return;
        }

        dataMahasiswa = "NIM: " + nim
                + "\nNama: " + nama
                + "\nProgram Studi: " + prodi
                + "\nJenis Kelamin: " + jenisKelamin;

        JOptionPane.showMessageDialog(this, "Data berhasil disimpan sementara.");
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnTampilActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTampilActionPerformed
        if (dataMahasiswa.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Belum ada data yang disimpan!");
        } else {
            txtHasil.setText(dataMahasiswa);
}
    }//GEN-LAST:event_btnTampilActionPerformed

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed
        txtNama.setText("");
        txtNIM.setText("");
        cmbProdi.setSelectedIndex(0);
        buttonGroup1.clearSelection();
        txtHasil.setText("");
        dataMahasiswa = "";
        txtNIM.requestFocus();
    }//GEN-LAST:event_btnResetActionPerformed

